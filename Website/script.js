const year = document.getElementById("year");
const languageToggle = document.getElementById("languageToggle");
let language = localStorage.getItem("panda-language") === "it" ? "it" : "en";

year.textContent = new Date().getFullYear();

function applyLanguage(nextLanguage) {
  language = nextLanguage;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach(element => {
    const value = translations[language][element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach(element => {
    const value = translations[language][element.dataset.i18nHtml];
    if (value) element.innerHTML = value;
  });
  languageToggle.querySelector(".language-current").textContent = language === "en" ? "EN" : "ITA";
  languageToggle.querySelector(".language-next").textContent = language === "en" ? "ITA" : "EN";
  localStorage.setItem("panda-language", language);
}

languageToggle.addEventListener("click", () => applyLanguage(language === "en" ? "it" : "en"));
applyLanguage(language);

const observer = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add("visible");
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.1 });

document.querySelectorAll(".reveal").forEach(element => observer.observe(element));
